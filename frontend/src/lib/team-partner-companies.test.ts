import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";

const source = (path: string) => readFileSync(new URL(path, import.meta.url), "utf8");

test("Team keeps people and partner companies separate", () => {
    const page = source("../app/dashboard/users/page.tsx");
    const service = source("../services/collaboration.service.ts");
    const acceptance = source("../app/(auth)/accept-company-invitation/page.tsx");
    const signupWizard = source("../components/collaborations/CompanyInvitationSignupWizard.tsx");
    const workerAcceptance = source("../app/(auth)/accept-invitation/page.tsx");
    const passwordCreation = source("../components/auth/PasswordCreationFields.tsx");
    const chooser = source("../components/users/TeamInvitationChooserDialog.tsx");
    const workerDialog = source("../components/users/UserCreateDialog.tsx");
    const en = source("../dictionaries/en.json");
    const es = source("../dictionaries/es.json");

    assert.match(page, /CollaborationManagementPanel/);
    assert.match(page, /TeamInvitationChooserDialog/);
    assert.match(page, /dict\.users\.partner_companies/);
    assert.match(page, /dict\.users\.accountants_info/);
    assert.match(page, /member\.role\?\.name === "accountant"/);
    assert.match(page, /get\("tab"\) === "companies"/);
    assert.doesNotMatch(page, /badge: companyTeam\.length/);
    assert.match(chooser, /onInvitePerson/);
    assert.match(chooser, /onInviteCompany/);
    assert.match(chooser, /CheckCircle2/);
    assert.match(chooser, /invite_person_bullets/);
    assert.match(workerDialog, /Input/);
    assert.match(workerDialog, /DocumentFormSelect/);
    assert.match(en, /"collaborations"/);
    assert.match(es, /"collaborations"/);
    assert.match(service, /inviteCompanyByEmail/);
    assert.match(service, /acceptCompanyInvitation/);
    assert.match(service, /declineCompanyInvitation/);
    assert.match(service, /getCompanyInvitationActivationStatus/);
    assert.match(service, /activateCompanyInvitation/);
    assert.match(service, /activateCompanyInvitationForExistingAccount/);
    assert.match(service, /declineCompanyInvitationWithoutAccount/);
    assert.match(service, /verifyCompanyInvitationAccess/);
    assert.match(service, /verifyCompanyInvitationCode/);
    assert.match(service, /\/api\/v1\/collaborations\/invitations/);
    assert.match(acceptance, /acceptCompanyInvitation/);
    assert.match(acceptance, /activateCompanyInvitation/);
    assert.match(acceptance, /existing-no-company/);
    assert.match(acceptance, /verifyCompanyInvitationAccess/);
    assert.match(acceptance, /verificationCode/);
    assert.match(acceptance, /verifyCompanyInvitationCode/);
    assert.match(acceptance, /non-admin/);
    assert.match(acceptance, /CompanyInvitationSignupWizard/);
    assert.match(acceptance, /window\.location\.hash/);
    assert.match(acceptance, /sessionStorage/);
    assert.doesNotMatch(acceptance, /login\?next=.*token/);
    assert.match(acceptance, /Código del correo/);
    assert.match(acceptance, /Email code/);
    assert.match(acceptance, /\/dashboard\/users\?tab=companies/);
    assert.match(signupWizard, /PasswordCreationFields/);
    assert.match(signupWizard, /WizardProgress/);
    assert.match(signupWizard, /onVerifyCode/);
    assert.match(signupWizard, /setStep\(2\)/);
    assert.match(workerAcceptance, /PasswordCreationFields/);
    assert.match(passwordCreation, /PasswordStrengthChecklist/);
    assert.match(passwordCreation, /Checkbox/);
    assert.match(passwordCreation, /EyeOff/);
});
