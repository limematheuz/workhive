from datetime import datetime
from app.schemas.work_session import WorkSessionCreate
from sqlalchemy import and_, or_
from sqlalchemy.orm import Session, joinedload, selectinload
from app.models.reservation import Reservation
from app.models.task_item import TaskItem
from app.models.work_session import WorkSession
from app.models.work_session_pause import WorkSessionPause
from app.models.user import User


def get_active_session_by_user(db: Session, user_id: int) -> WorkSession | None:
    sessions = get_active_sessions_by_user(db, user_id)
    return sessions[0] if sessions else None


def get_active_session_by_user_for_update(
    db: Session, user_id: int
) -> WorkSession | None:
    return (
        db.query(WorkSession)
        .filter(WorkSession.user_id == user_id, WorkSession.end_time.is_(None))
        .order_by(WorkSession.id.desc())
        .with_for_update()
        .first()
    )


def get_active_pause_for_update(
    db: Session, work_session_id: int
) -> WorkSessionPause | None:
    return (
        db.query(WorkSessionPause)
        .filter(
            WorkSessionPause.work_session_id == work_session_id,
            WorkSessionPause.ended_at.is_(None),
        )
        .with_for_update()
        .first()
    )


def get_active_sessions_by_user(
    db: Session, user_id: int
) -> list[WorkSession]:
    return (
        db.query(WorkSession)
        .options(selectinload(WorkSession.pauses))
        .filter(WorkSession.user_id == user_id)
        .filter(WorkSession.end_time.is_(None))
        .order_by(WorkSession.id.desc())
        .all()
    )


def get_work_session_by_id(
    db: Session,
    session_id: int,
    user_id: int,
    location_ids: set[int] | None = None,
    for_update: bool = False,
) -> WorkSession | None:
    location_loader = (
        selectinload(WorkSession.location)
        if for_update
        else joinedload(WorkSession.location)
    )
    query = (
        db.query(WorkSession)
        # PostgreSQL does not allow FOR UPDATE on the nullable side of the
        # outer join generated by joinedload(location).  Lock only the
        # session row and load its location separately when mutating it.
        .options(selectinload(WorkSession.pauses), location_loader)
        .filter(WorkSession.id == session_id)
        .filter(WorkSession.user_id == user_id)
    )
    if location_ids is not None:
        query = query.filter(WorkSession.location_id.in_(location_ids))
    if for_update:
        query = query.with_for_update()
    return query.first()


def get_work_session_by_user(
    db: Session,
    user_id: int,
    skip: int = 0,
    limit: int = 100,
    location_ids: set[int] | None = None,
) -> list[WorkSession]:
    query = (
        db.query(WorkSession)
        .options(selectinload(WorkSession.pauses), joinedload(WorkSession.location))
        .filter(WorkSession.user_id == user_id)
    )
    if location_ids is not None:
        query = query.filter(WorkSession.location_id.in_(location_ids))
    return query.offset(skip).limit(limit).all()


def create_work_session(
    db: Session, user_id: int, session_data: WorkSessionCreate, start_time: datetime
) -> WorkSession:
    db_work_session = WorkSession(
        **session_data.model_dump(), start_time=start_time, user_id=user_id
    )
    db.add(db_work_session)
    db.commit()
    db.refresh(db_work_session)
    return db_work_session


def close_work_session(
    db: Session, db_session: WorkSession, end_time: datetime
) -> WorkSession:
    db_session.end_time = end_time
    db.add(db_session)
    db.commit()
    db.refresh(db_session)
    return db_session


def get_closed_sessions_by_user(
    db: Session,
    user_id: int,
    start_date: datetime | None = None,
    location_ids: set[int] | None = None,
) -> list[WorkSession]:
    query = (
        db.query(WorkSession)
        .options(selectinload(WorkSession.pauses))
        .filter(WorkSession.user_id == user_id)
        .filter(WorkSession.end_time.isnot(None))
    )
    if start_date:
        query = query.filter(WorkSession.start_time >= start_date)
    if location_ids is not None:
        query = query.filter(WorkSession.location_id.in_(location_ids))
    return query.all()


def get_distinct_location_ids_by_user(
    db: Session,
    user_id: int,
    start_date: datetime | None = None,
    location_ids: set[int] | None = None,
) -> list[int]:
    query = (
        db.query(WorkSession.location_id)
        .filter(WorkSession.user_id == user_id)
        .filter(WorkSession.location_id.isnot(None))
    )
    if start_date:
        query = query.filter(WorkSession.start_time >= start_date)
    if location_ids is not None:
        query = query.filter(WorkSession.location_id.in_(location_ids))
    results = query.distinct().all()
    return [r[0] for r in results]


def get_sessions_by_task(db: Session, task_item_id: int) -> list[WorkSession]:
    return (
        db.query(WorkSession)
        .options(selectinload(WorkSession.pauses))
        .filter(WorkSession.task_item_id == task_item_id)
        .order_by(WorkSession.start_time.asc())
        .all()
    )


def get_sessions_by_tasks(db: Session, task_item_ids: list[int]) -> list[WorkSession]:
    if not task_item_ids:
        return []
    return (
        db.query(WorkSession)
        .options(joinedload(WorkSession.user), selectinload(WorkSession.pauses))
        .filter(WorkSession.task_item_id.in_(task_item_ids))
        .order_by(WorkSession.task_item_id.asc(), WorkSession.start_time.asc())
        .all()
    )


def get_visible_sessions_by_task(
    db: Session, company_id: int, task_item_id: int
) -> list[WorkSession]:
    return (
        db.query(WorkSession)
        .options(selectinload(WorkSession.pauses))
        .join(User, WorkSession.user_id == User.id)
        .outerjoin(TaskItem, WorkSession.task_item_id == TaskItem.id)
        .outerjoin(
            Reservation,
            TaskItem.checkout_reservation_id == Reservation.id,
        )
        .filter(
            WorkSession.task_item_id == task_item_id,
            User.is_active.is_(True),
            or_(
                User.company_id == company_id,
                and_(
                    User.company_id != company_id,
                    TaskItem.company_id == User.company_id,
                    Reservation.owner_company_id == company_id,
                ),
            ),
        )
        .order_by(WorkSession.start_time.asc())
        .all()
    )


